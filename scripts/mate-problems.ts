/**
 * Generates mate problems for the site: the computer plays games against itself, and every play phase position where
 * the side to move mates in 1 to 3 checking moves with a single first move becomes a problem, with its solution line.
 * Problems already in packages/protocol/src/mates.ts are kept with their ids, so running it again only adds new ones.
 *
 *   node scripts/mate-problems.ts [--games 200] [--seed 1] [--workers 4]
 */
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { availableParallelism } from 'node:os';
import { parseArgs } from 'node:util';
import { Worker, isMainThread, parentPort, workerData } from 'node:worker_threads';
import { chooseMove, longestDefense, mateDistance, mateSolutions } from '../packages/bot/src/index.ts';
import { Game, MODES, applyMove, initialPosition, isMarshalAttacked, moveToString, opposite, parseFen, toFen } from '../packages/engine/src/index.ts';
import type { Position } from '../packages/engine/src/index.ts';
import type { MateProblem } from '../packages/protocol/src/index.ts';
import { MATE_PROBLEMS } from '../packages/protocol/src/mates.ts';

const MAX_MOVES = 3;
const MAX_PLIES = 400;
const OUTPUT = new URL('../packages/protocol/src/mates.ts', import.meta.url);

/** The solution from a position with a single first move: the attacker's moves and the longest defense in between. */
const solutionLine = (start: Position, moves: number): string[] => {
  const line: string[] = [];
  let position = start;
  for (let left = moves; left >= 1; left--) {
    const move = mateSolutions(position, left)[0]!;
    line.push(moveToString(move));
    position = applyMove(position, move);
    if (left === 1) break;
    const defense = longestDefense(position, left - 1)!;
    line.push(moveToString(defense));
    position = applyMove(position, defense);
  }
  return line;
};

/** Plays one game and returns its problems, at most one for each length, so one game does not fill the set. */
const problemsOfGame = (index: number, seed: number): Omit<MateProblem, 'id'>[] => {
  let state = (seed * 7919 + index * 104729) % 2147483647 || 1;
  const random = () => (state = (state * 16807) % 2147483647) / 2147483647;
  const game = new Game(initialPosition(MODES[index % MODES.length]!));
  const found = new Map<number, Omit<MateProblem, 'id'>>();
  for (let ply = 0; ply < MAX_PLIES && !game.outcome; ply++) {
    const position = game.position;
    // A Marshal left attacked on the opponent's move only happens right after the draft: not a problem position.
    if (position.phase === 'play' && !isMarshalAttacked(position, opposite(position.turn))) {
      const moves = mateDistance(position, MAX_MOVES);
      if (moves !== null && !found.has(moves) && mateSolutions(position, moves).length === 1) {
        found.set(moves, { fen: toFen(position), moves, line: solutionLine(position, moves) });
      }
    }
    game.play(chooseMove(position, random() < 0.5 ? 3 : 2, { random }));
  }
  return [...found.values()];
};

const idOf = (fen: string): string => createHash('sha256').update(fen).digest('hex').slice(0, 8);

const write = (problems: readonly MateProblem[]): void => {
  const modeOf = (problem: MateProblem) => MODES.indexOf(parseFen(problem.fen).mode);
  const sorted = [...problems].sort((a, b) => modeOf(a) - modeOf(b) || a.moves - b.moves || a.id.localeCompare(b.id));
  const body = sorted.map((problem) => `  ${JSON.stringify(problem)},`).join('\n');
  writeFileSync(
    OUTPUT,
    `import type { MateProblem } from './index.ts';\n\n` +
      `// Generated by scripts/mate-problems.ts from games the computer played against itself. Do not edit by hand.\n` +
      `export const MATE_PROBLEMS: readonly MateProblem[] = [\n${body}\n];\n`,
  );
};

if (isMainThread) {
  const { values } = parseArgs({ options: { games: { type: 'string', default: '200' }, seed: { type: 'string', default: '1' }, workers: { type: 'string' } } });
  const games = Number(values.games);
  const seed = Number(values.seed);
  const workers = Math.max(1, Math.min(games, Number(values.workers ?? Math.max(1, availableParallelism() - 1))));
  const known = new Map(MATE_PROBLEMS.map((problem) => [problem.fen, problem]));
  const before = known.size;
  let done = 0;
  await Promise.all(
    Array.from({ length: workers }, (_, worker) =>
      new Promise<void>((resolve, reject) => {
        const indexes = Array.from({ length: games }, (_, i) => i).filter((i) => i % workers === worker);
        const thread = new Worker(new URL(import.meta.url), { workerData: { indexes, seed } });
        thread.on('message', (problems: Omit<MateProblem, 'id'>[]) => {
          for (const problem of problems) if (!known.has(problem.fen)) known.set(problem.fen, { id: idOf(problem.fen), ...problem });
          done++;
          process.stdout.write(`\r${done}/${games} games, ${known.size - before} new problems`);
        });
        thread.on('error', reject);
        thread.on('exit', () => resolve());
      }),
    ),
  );
  write([...known.values()]);
  process.stdout.write(`\nWrote ${known.size} problems (${known.size - before} new).\n`);
} else {
  const { indexes, seed } = workerData as { indexes: number[]; seed: number };
  for (const index of indexes) parentPort!.postMessage(problemsOfGame(index, seed));
}
